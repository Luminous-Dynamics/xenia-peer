//! Quorum-witnessed, rollback-resistant checkpoints for durable operation WALs.
//!
//! This module verifies signed checkpoint statements and local WAL recovery.
//! It does not implement a network witness service or durable witness database.
//! A production witness must atomically compare-and-advance its stored journal
//! head before signing; otherwise a quorum of signatures could still certify
//! conflicting forks if signers equivocate.
//!
//! The quorum policy assumes at most f Byzantine witness identities, requires
//! n >= 3f + 1 configured witnesses, and accepts only 2f + 1 distinct
//! signatures. Any two accepted quorums therefore intersect in at least f + 1
//! witnesses, including at least one honest non-equivocating witness.
//!
//! Freshness reads use a caller-generated, single-use challenge nonce. Each
//! witness must sign the requested nonce together with its *currently stored*
//! latest checkpoint. A replayed signed checkpoint without the fresh nonce is
//! not a valid freshness response.
//!
//! The WAL's local BLAKE3 chain remains an integrity mechanism, not an
//! authenticity mechanism. Recovery verification below compares a fully
//! replayed current head and the WAL's captured verified prefix at the trusted
//! checkpoint sequence. The caller must first verify the checkpoint quorum,
//! and must obtain the WAL object from a complete successful replay.

use std::collections::HashMap;

use ed25519_dalek::{Signature, VerifyingKey};

use crate::operation_evidence_wal::{
    DurableOperationEvidenceJournal, DurableOperationJournalHead,
};

/// Current schema for signed journal-head checkpoints.
pub const JOURNAL_HEAD_CHECKPOINT_SCHEMA_VERSION: u16 = 1;
/// Upper bound on the number of configured witness identities.
pub const MAX_JOURNAL_HEAD_WITNESSES: usize = 16;
/// Domain separator used for ordinary checkpoint signatures.
const CHECKPOINT_DOMAIN: &[u8] = b"XENIA-JOURNAL-HEAD-CHECKPOINT-V1\0";
/// Domain separator used for nonce-bound latest-head read signatures.
const CHALLENGE_DOMAIN: &[u8] = b"XENIA-JOURNAL-HEAD-CHALLENGE-READ-V1\0";

/// Stable identifier for one logical operation journal.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct JournalId(pub [u8; 16]);

/// Stable identity of an independently administered witness.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct JournalWitnessId(pub [u8; 16]);

/// A configured Ed25519 public key for one witness key epoch.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct JournalWitnessPublicKey {
    /// Stable witness identity; do not reuse for another administrative domain.
    pub witness_id: JournalWitnessId,
    /// Monotonic key epoch for explicit witness key rotation.
    pub key_epoch: u64,
    /// Ed25519 verifying key bytes.
    pub verifying_key: [u8; 32],
}

/// Immutable policy for verifying a Byzantine quorum of journal witnesses.
#[derive(Clone, Debug)]
pub struct JournalHeadAnchorPolicy {
    witnesses: HashMap<JournalWitnessId, JournalWitnessPublicKey>,
    max_byzantine_faults: usize,
    required_quorum: usize,
}

/// A monotonic checkpoint statement for one operation journal.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct JournalHeadCheckpoint {
    /// Checkpoint wire/schema version.
    pub schema_version: u16,
    /// Stable ID of the operation journal being anchored.
    pub journal_id: JournalId,
    /// Monotonic checkpoint sequence, independent of the WAL record sequence.
    pub checkpoint_sequence: u64,
    /// Fully replayed WAL head being anchored.
    pub head: DurableOperationJournalHead,
    /// Digest of the previous accepted checkpoint, or zero for the first.
    pub previous_checkpoint_digest: [u8; 32],
}

/// One witness signature over a checkpoint or nonce-bound read statement.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct JournalWitnessSignature {
    /// Configured witness identity.
    pub witness_id: JournalWitnessId,
    /// Exact public-key epoch used to verify this signature.
    pub key_epoch: u64,
    /// Ed25519 signature bytes.
    pub signature: [u8; 64],
}

/// A checkpoint statement accompanied by its write-quorum signatures.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SignedJournalHeadCheckpoint {
    /// Checkpoint being accepted.
    pub checkpoint: JournalHeadCheckpoint,
    /// Distinct witness signatures over the canonical checkpoint digest.
    pub signatures: Vec<JournalWitnessSignature>,
}

/// Single-use caller challenge for a current-head read.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct JournalHeadReadChallenge {
    /// Journal whose latest checkpoint is requested.
    pub journal_id: JournalId,
    /// Fresh cryptographically random nonce generated by the verifier.
    pub nonce: [u8; 32],
}

/// A nonce-bound response asserting the witness quorum's current latest head.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SignedJournalHeadRead {
    /// Latest checkpoint asserted by the witnesses at read time.
    pub checkpoint: JournalHeadCheckpoint,
    /// Exact challenge nonce issued by the reader.
    pub challenge_nonce: [u8; 32],
    /// Witness signatures over checkpoint digest plus challenge nonce.
    pub signatures: Vec<JournalWitnessSignature>,
}

/// A checkpoint that has passed signature and monotonic-chain verification.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct VerifiedJournalHeadCheckpoint {
    checkpoint: JournalHeadCheckpoint,
    digest: [u8; 32],
}

impl VerifiedJournalHeadCheckpoint {
    /// Return the checkpoint statement that was verified.
    pub fn checkpoint(&self) -> &JournalHeadCheckpoint {
        &self.checkpoint
    }

    /// Return the canonical digest signed by the witness quorum.
    pub fn digest(&self) -> [u8; 32] {
        self.digest
    }
}

/// Errors returned by witness policy, checkpoint, and recovery verification.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum JournalHeadAnchorError {
    /// No witness keys were configured.
    EmptyWitnessSet,
    /// Witness count exceeds the implementation bound.
    TooManyWitnesses,
    /// Witness count cannot tolerate the configured Byzantine fault count.
    InsufficientWitnessesForFaultBound,
    /// Witness ID appears more than once.
    DuplicateWitness,
    /// A witness key epoch must be nonzero.
    InvalidWitnessKeyEpoch,
    /// A configured Ed25519 public key is invalid.
    InvalidWitnessPublicKey,
    /// Checkpoint schema is not supported.
    UnsupportedCheckpointSchema,
    /// Checkpoint sequence is zero or not the expected next value.
    NonMonotonicCheckpointSequence,
    /// The checkpoint does not extend the previously verified checkpoint.
    PreviousCheckpointMismatch,
    /// Checkpoint refers to a different logical journal.
    JournalIdMismatch,
    /// Authenticated session fingerprint changed within one journal.
    SessionFingerprintMismatch,
    /// Logical clock domain changed within one journal.
    ClockDomainMismatch,
    /// WAL journal sequence regressed.
    WalSequenceRegression,
    /// Same WAL sequence is presented with a different head.
    WalHeadFork,
    /// Highest admitted operation sequence regressed.
    OperationSequenceRegression,
    /// Fewer than the required number of distinct signatures were supplied.
    InsufficientSignatures,
    /// One witness appears more than once in a signature set.
    DuplicateWitnessSignature,
    /// Signature belongs to an unconfigured witness.
    UnknownWitness,
    /// Signature key epoch differs from the configured witness key epoch.
    WitnessKeyEpochMismatch,
    /// Signature verification failed.
    InvalidWitnessSignature,
    /// A challenge response names a different journal or nonce.
    ChallengeMismatch,
    /// Local WAL is behind the trusted checkpoint.
    LocalJournalBehindAnchor,
    /// Local WAL does not retain the anchored sequence.
    AnchoredPrefixUnavailable,
    /// Local WAL's verified prefix does not equal the trusted checkpoint.
    AnchoredPrefixMismatch,
}

impl JournalHeadAnchorPolicy {
    /// Build a policy requiring a 2f+1 quorum from at least 3f+1 witnesses.
    ///
    /// Witnesses must represent independent administrative/storage failure
    /// domains in production. Four witnesses with f=1 require three distinct
    /// signatures. This constructor validates key material and quorum math;
    /// it cannot prove organizational independence.
    pub fn new(
        witnesses: Vec<JournalWitnessPublicKey>,
        max_byzantine_faults: usize,
    ) -> Result<Self, JournalHeadAnchorError> {
        if witnesses.is_empty() {
            return Err(JournalHeadAnchorError::EmptyWitnessSet);
        }
        if witnesses.len() > MAX_JOURNAL_HEAD_WITNESSES {
            return Err(JournalHeadAnchorError::TooManyWitnesses);
        }
        let minimum = max_byzantine_faults
            .checked_mul(3)
            .and_then(|value| value.checked_add(1))
            .ok_or(JournalHeadAnchorError::InsufficientWitnessesForFaultBound)?;
        if witnesses.len() < minimum {
            return Err(JournalHeadAnchorError::InsufficientWitnessesForFaultBound);
        }
        let required_quorum = max_byzantine_faults
            .checked_mul(2)
            .and_then(|value| value.checked_add(1))
            .ok_or(JournalHeadAnchorError::InsufficientWitnessesForFaultBound)?;
        let mut configured = HashMap::with_capacity(witnesses.len());
        for witness in witnesses {
            if witness.key_epoch == 0 {
                return Err(JournalHeadAnchorError::InvalidWitnessKeyEpoch);
            }
            VerifyingKey::from_bytes(&witness.verifying_key)
                .map_err(|_| JournalHeadAnchorError::InvalidWitnessPublicKey)?;
            if configured.insert(witness.witness_id, witness).is_some() {
                return Err(JournalHeadAnchorError::DuplicateWitness);
            }
        }
        Ok(Self {
            witnesses: configured,
            max_byzantine_faults,
            required_quorum,
        })
    }

    /// Return the assumed Byzantine fault bound.
    pub fn max_byzantine_faults(&self) -> usize {
        self.max_byzantine_faults
    }

    /// Return the minimum number of distinct witness signatures required.
    pub fn required_quorum(&self) -> usize {
        self.required_quorum
    }

    /// Verify a signed checkpoint and its exact monotonic predecessor.
    ///
    /// Pass None only for a journal's genesis checkpoint (sequence 1, zero
    /// previous digest). The caller must preserve the returned verified value
    /// or reload it from independently trusted storage before accepting a
    /// later checkpoint.
    pub fn verify_checkpoint(
        &self,
        signed: &SignedJournalHeadCheckpoint,
        previous: Option<&VerifiedJournalHeadCheckpoint>,
    ) -> Result<VerifiedJournalHeadCheckpoint, JournalHeadAnchorError> {
        validate_checkpoint_transition(&signed.checkpoint, previous)?;
        let digest = checkpoint_digest(&signed.checkpoint);
        self.verify_signatures(&signed.signatures, &digest)?;
        Ok(VerifiedJournalHeadCheckpoint {
            checkpoint: signed.checkpoint,
            digest,
        })
    }

    /// Verify a quorum-signed response to a fresh latest-head challenge.
    ///
    /// The expected challenge must be generated with a cryptographically secure
    /// random source and must not be reused. Honest witnesses sign only after
    /// reading their currently committed latest checkpoint.
    pub fn verify_challenged_read(
        &self,
        response: &SignedJournalHeadRead,
        expected: JournalHeadReadChallenge,
        previous: Option<&VerifiedJournalHeadCheckpoint>,
    ) -> Result<VerifiedJournalHeadCheckpoint, JournalHeadAnchorError> {
        if response.challenge_nonce != expected.nonce
            || response.checkpoint.journal_id != expected.journal_id
        {
            return Err(JournalHeadAnchorError::ChallengeMismatch);
        }
        validate_checkpoint_transition(&response.checkpoint, previous)?;
        let digest = challenged_read_digest(&response.checkpoint, response.challenge_nonce);
        self.verify_signatures(&response.signatures, &digest)?;
        Ok(VerifiedJournalHeadCheckpoint {
            checkpoint: response.checkpoint,
            digest: checkpoint_digest(&response.checkpoint),
        })
    }

    fn verify_signatures(
        &self,
        signatures: &[JournalWitnessSignature],
        message_digest: &[u8; 32],
    ) -> Result<(), JournalHeadAnchorError> {
        if signatures.len() < self.required_quorum {
            return Err(JournalHeadAnchorError::InsufficientSignatures);
        }
        let mut seen = HashMap::<JournalWitnessId, ()>::with_capacity(signatures.len());
        for signature in signatures {
            if seen.insert(signature.witness_id, ()).is_some() {
                return Err(JournalHeadAnchorError::DuplicateWitnessSignature);
            }
            let witness = self
                .witnesses
                .get(&signature.witness_id)
                .ok_or(JournalHeadAnchorError::UnknownWitness)?;
            if signature.key_epoch != witness.key_epoch {
                return Err(JournalHeadAnchorError::WitnessKeyEpochMismatch);
            }
            let verifying_key = VerifyingKey::from_bytes(&witness.verifying_key)
                .map_err(|_| JournalHeadAnchorError::InvalidWitnessPublicKey)?;
            let signature = Signature::from_bytes(&signature.signature);
            verifying_key
                .verify_strict(message_digest, &signature)
                .map_err(|_| JournalHeadAnchorError::InvalidWitnessSignature)?;
        }
        Ok(())
    }
}

/// Verify that the local WAL is at least as new as a trusted checkpoint and
/// that its fully verified replay contains the exact anchored prefix.
///
/// The WAL object must have been opened successfully, which performs complete
/// record/state/hash replay and torn-tail handling. If the local WAL has
/// advanced beyond the checkpoint, the exact prefix head captured during that
/// replay must match the external anchor. This rejects an older snapshot and a
/// same-sequence fork even when the restored WAL is internally hash-consistent.
pub fn verify_local_journal_recovery(
    verified_anchor: &VerifiedJournalHeadCheckpoint,
    journal_id: JournalId,
    journal: &DurableOperationEvidenceJournal,
) -> Result<(), JournalHeadAnchorError> {
    let checkpoint = verified_anchor.checkpoint();
    if checkpoint.journal_id != journal_id {
        return Err(JournalHeadAnchorError::JournalIdMismatch);
    }
    let current = journal.head_candidate();
    if current.session_fingerprint != checkpoint.head.session_fingerprint {
        return Err(JournalHeadAnchorError::SessionFingerprintMismatch);
    }
    if current.clock_domain != checkpoint.head.clock_domain {
        return Err(JournalHeadAnchorError::ClockDomainMismatch);
    }
    if current.journal_sequence < checkpoint.head.journal_sequence {
        return Err(JournalHeadAnchorError::LocalJournalBehindAnchor);
    }
    let prefix = journal
        .verified_head_at_sequence(checkpoint.head.journal_sequence)
        .ok_or(JournalHeadAnchorError::AnchoredPrefixUnavailable)?;
    if prefix != checkpoint.head {
        return Err(JournalHeadAnchorError::AnchoredPrefixMismatch);
    }
    Ok(())
}

fn validate_checkpoint_transition(
    checkpoint: &JournalHeadCheckpoint,
    previous: Option<&VerifiedJournalHeadCheckpoint>,
) -> Result<(), JournalHeadAnchorError> {
    if checkpoint.schema_version != JOURNAL_HEAD_CHECKPOINT_SCHEMA_VERSION {
        return Err(JournalHeadAnchorError::UnsupportedCheckpointSchema);
    }
    match previous {
        None => {
            if checkpoint.checkpoint_sequence != 1
                || checkpoint.previous_checkpoint_digest != [0; 32]
            {
                return Err(JournalHeadAnchorError::NonMonotonicCheckpointSequence);
            }
        }
        Some(previous) => {
            let prior = previous.checkpoint();
            let expected_sequence = prior
                .checkpoint_sequence
                .checked_add(1)
                .ok_or(JournalHeadAnchorError::NonMonotonicCheckpointSequence)?;
            if checkpoint.checkpoint_sequence != expected_sequence {
                return Err(JournalHeadAnchorError::NonMonotonicCheckpointSequence);
            }
            if checkpoint.journal_id != prior.journal_id {
                return Err(JournalHeadAnchorError::JournalIdMismatch);
            }
            if checkpoint.previous_checkpoint_digest != previous.digest() {
                return Err(JournalHeadAnchorError::PreviousCheckpointMismatch);
            }
            if checkpoint.head.session_fingerprint != prior.head.session_fingerprint {
                return Err(JournalHeadAnchorError::SessionFingerprintMismatch);
            }
            if checkpoint.head.clock_domain != prior.head.clock_domain {
                return Err(JournalHeadAnchorError::ClockDomainMismatch);
            }
            if checkpoint.head.journal_sequence < prior.head.journal_sequence {
                return Err(JournalHeadAnchorError::WalSequenceRegression);
            }
            if checkpoint.head.journal_sequence == prior.head.journal_sequence
                && checkpoint.head != prior.head
            {
                return Err(JournalHeadAnchorError::WalHeadFork);
            }
            if operation_sequence_regressed(
                prior.head.last_operation_sequence,
                checkpoint.head.last_operation_sequence,
            ) {
                return Err(JournalHeadAnchorError::OperationSequenceRegression);
            }
        }
    }
    Ok(())
}

fn operation_sequence_regressed(previous: Option<u64>, observed: Option<u64>) -> bool {
    match (previous, observed) {
        (Some(_), None) => true,
        (Some(previous), Some(observed)) => observed < previous,
        (None, _) => false,
    }
}

fn checkpoint_digest(checkpoint: &JournalHeadCheckpoint) -> [u8; 32] {
    let mut hasher = blake3::Hasher::new();
    hasher.update(CHECKPOINT_DOMAIN);
    hasher.update(&checkpoint.schema_version.to_le_bytes());
    hasher.update(&checkpoint.journal_id.0);
    hasher.update(&checkpoint.checkpoint_sequence.to_le_bytes());
    hash_journal_head(&mut hasher, checkpoint.head);
    hasher.update(&checkpoint.previous_checkpoint_digest);
    *hasher.finalize().as_bytes()
}

fn challenged_read_digest(
    checkpoint: &JournalHeadCheckpoint,
    challenge_nonce: [u8; 32],
) -> [u8; 32] {
    let mut hasher = blake3::Hasher::new();
    hasher.update(CHALLENGE_DOMAIN);
    hasher.update(&checkpoint_digest(checkpoint));
    hasher.update(&challenge_nonce);
    *hasher.finalize().as_bytes()
}

fn hash_journal_head(hasher: &mut blake3::Hasher, head: DurableOperationJournalHead) {
    hasher.update(&head.session_fingerprint);
    hasher.update(&head.clock_domain.to_le_bytes());
    hasher.update(&head.journal_sequence.to_le_bytes());
    hasher.update(&head.wal_chain_digest);
    match head.last_operation_sequence {
        Some(sequence) => {
            hasher.update(&[1]);
            hasher.update(&sequence.to_le_bytes());
        }
        None => {
            hasher.update(&[0]);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use ed25519_dalek::{Signer, SigningKey};

    struct TestWitness {
        public: JournalWitnessPublicKey,
        signing: SigningKey,
    }

    fn test_policy() -> (JournalHeadAnchorPolicy, Vec<TestWitness>) {
        let witnesses: Vec<_> = (1_u8..=4)
            .map(|id| {
                let signing = SigningKey::from_bytes(&[id; 32]);
                let public = JournalWitnessPublicKey {
                    witness_id: JournalWitnessId([id; 16]),
                    key_epoch: 1,
                    verifying_key: signing.verifying_key().to_bytes(),
                };
                TestWitness { public, signing }
            })
            .collect();
        let policy = JournalHeadAnchorPolicy::new(
            witnesses.iter().map(|witness| witness.public).collect(),
            1,
        )
        .unwrap_or_else(|error| panic!("policy failed: {error:?}"));
        (policy, witnesses)
    }

    fn head(
        journal_sequence: u64,
        wal_chain_digest: [u8; 32],
        last_operation_sequence: Option<u64>,
    ) -> DurableOperationJournalHead {
        DurableOperationJournalHead {
            session_fingerprint: [7; 32],
            clock_domain: 9,
            journal_sequence,
            wal_chain_digest,
            last_operation_sequence,
        }
    }

    fn checkpoint(
        sequence: u64,
        head: DurableOperationJournalHead,
        previous_checkpoint_digest: [u8; 32],
    ) -> JournalHeadCheckpoint {
        JournalHeadCheckpoint {
            schema_version: JOURNAL_HEAD_CHECKPOINT_SCHEMA_VERSION,
            journal_id: JournalId([4; 16]),
            checkpoint_sequence: sequence,
            head,
            previous_checkpoint_digest,
        }
    }

    fn sign_checkpoint(
        checkpoint: JournalHeadCheckpoint,
        witnesses: &[TestWitness],
        selected: &[usize],
    ) -> SignedJournalHeadCheckpoint {
        let digest = checkpoint_digest(&checkpoint);
        let signatures = selected
            .iter()
            .map(|index| {
                let witness = &witnesses[*index];
                JournalWitnessSignature {
                    witness_id: witness.public.witness_id,
                    key_epoch: witness.public.key_epoch,
                    signature: witness.signing.sign(&digest).to_bytes(),
                }
            })
            .collect();
        SignedJournalHeadCheckpoint {
            checkpoint,
            signatures,
        }
    }

    fn sign_read(
        checkpoint: JournalHeadCheckpoint,
        nonce: [u8; 32],
        witnesses: &[TestWitness],
        selected: &[usize],
    ) -> SignedJournalHeadRead {
        let digest = challenged_read_digest(&checkpoint, nonce);
        let signatures = selected
            .iter()
            .map(|index| {
                let witness = &witnesses[*index];
                JournalWitnessSignature {
                    witness_id: witness.public.witness_id,
                    key_epoch: witness.public.key_epoch,
                    signature: witness.signing.sign(&digest).to_bytes(),
                }
            })
            .collect();
        SignedJournalHeadRead {
            checkpoint,
            challenge_nonce: nonce,
            signatures,
        }
    }

    #[test]
    fn four_witness_policy_requires_three_signatures() {
        let (policy, witnesses) = test_policy();
        assert_eq!(policy.max_byzantine_faults(), 1);
        assert_eq!(policy.required_quorum(), 3);
        let signed = sign_checkpoint(checkpoint(1, head(0, [0; 32], None), [0; 32]), &witnesses, &[0, 1, 2]);
        assert!(policy.verify_checkpoint(&signed, None).is_ok());
        let insufficient = sign_checkpoint(signed.checkpoint, &witnesses, &[0, 1]);
        assert_eq!(
            policy.verify_checkpoint(&insufficient, None),
            Err(JournalHeadAnchorError::InsufficientSignatures)
        );
    }

    #[test]
    fn checkpoint_chain_rejects_forks_and_regressions() {
        let (policy, witnesses) = test_policy();
        let first = sign_checkpoint(checkpoint(1, head(2, [2; 32], Some(1)), [0; 32]), &witnesses, &[0, 1, 2]);
        let verified_first = policy
            .verify_checkpoint(&first, None)
            .unwrap_or_else(|error| panic!("first checkpoint failed: {error:?}"));

        let second = sign_checkpoint(
            checkpoint(2, head(3, [3; 32], Some(2)), verified_first.digest()),
            &witnesses,
            &[0, 1, 2],
        );
        let verified_second = policy
            .verify_checkpoint(&second, Some(&verified_first))
            .unwrap_or_else(|error| panic!("second checkpoint failed: {error:?}"));

        let fork = sign_checkpoint(
            checkpoint(3, head(3, [99; 32], Some(2)), verified_second.digest()),
            &witnesses,
            &[0, 1, 2],
        );
        assert_eq!(
            policy.verify_checkpoint(&fork, Some(&verified_second)),
            Err(JournalHeadAnchorError::WalHeadFork)
        );

        let regression = sign_checkpoint(
            checkpoint(3, head(2, [2; 32], Some(1)), verified_second.digest()),
            &witnesses,
            &[0, 1, 2],
        );
        assert_eq!(
            policy.verify_checkpoint(&regression, Some(&verified_second)),
            Err(JournalHeadAnchorError::WalSequenceRegression)
        );
    }

    #[test]
    fn checkpoint_verification_rejects_duplicate_and_old_key_epoch() {
        let (policy, witnesses) = test_policy();
        let mut signed = sign_checkpoint(checkpoint(1, head(0, [0; 32], None), [0; 32]), &witnesses, &[0, 1, 2]);
        signed.signatures[1] = signed.signatures[0];
        assert_eq!(
            policy.verify_checkpoint(&signed, None),
            Err(JournalHeadAnchorError::DuplicateWitnessSignature)
        );

        let mut stale_key = sign_checkpoint(checkpoint(1, head(0, [0; 32], None), [0; 32]), &witnesses, &[0, 1, 2]);
        stale_key.signatures[0].key_epoch = 2;
        assert_eq!(
            policy.verify_checkpoint(&stale_key, None),
            Err(JournalHeadAnchorError::WitnessKeyEpochMismatch)
        );
    }

    #[test]
    fn checkpoint_signatures_bind_every_head_field() {
        let (policy, witnesses) = test_policy();
        let signed = sign_checkpoint(checkpoint(1, head(0, [0; 32], None), [0; 32]), &witnesses, &[0, 1, 2]);
        let mut tampered = signed.clone();
        tampered.checkpoint.head.clock_domain = 10;
        assert_eq!(
            policy.verify_checkpoint(&tampered, None),
            Err(JournalHeadAnchorError::InvalidWitnessSignature)
        );
    }

    #[test]
    fn challenge_reads_are_nonce_bound_and_chain_checked() {
        let (policy, witnesses) = test_policy();
        let checkpoint = checkpoint(1, head(0, [0; 32], None), [0; 32]);
        let nonce = [88; 32];
        let response = sign_read(checkpoint, nonce, &witnesses, &[0, 1, 2]);
        let challenge = JournalHeadReadChallenge {
            journal_id: checkpoint.journal_id,
            nonce,
        };
        assert!(policy.verify_challenged_read(&response, challenge, None).is_ok());

        let wrong_challenge = JournalHeadReadChallenge {
            journal_id: checkpoint.journal_id,
            nonce: [89; 32],
        };
        assert_eq!(
            policy.verify_challenged_read(&response, wrong_challenge, None),
            Err(JournalHeadAnchorError::ChallengeMismatch)
        );
    }

    #[test]
    fn local_recovery_requires_exact_anchored_prefix() {
        let (policy, witnesses) = test_policy();
        let anchored_head = head(4, [4; 32], Some(3));
        let signed = sign_checkpoint(checkpoint(1, anchored_head, [0; 32]), &witnesses, &[0, 1, 2]);
        let verified = policy
            .verify_checkpoint(&signed, None)
            .unwrap_or_else(|error| panic!("checkpoint failed: {error:?}"));

        let current = head(6, [6; 32], Some(4));
        let exact_prefix = anchored_head;
        verify_recovered_heads(&verified, JournalId([4; 16]), current, Some(exact_prefix))
            .unwrap_or_else(|error| panic!("exact prefix rejected: {error:?}"));
        assert_eq!(
            verify_recovered_heads(&verified, JournalId([4; 16]), head(3, [3; 32], Some(2)), None),
            Err(JournalHeadAnchorError::LocalJournalBehindAnchor)
        );
        assert_eq!(
            verify_recovered_heads(&verified, JournalId([4; 16]), current, Some(head(4, [99; 32], Some(3)))),
            Err(JournalHeadAnchorError::AnchoredPrefixMismatch)
        );
    }
}

fn verify_recovered_heads(
    verified_anchor: &VerifiedJournalHeadCheckpoint,
    journal_id: JournalId,
    current: DurableOperationJournalHead,
    prefix: Option<DurableOperationJournalHead>,
) -> Result<(), JournalHeadAnchorError> {
    let checkpoint = verified_anchor.checkpoint();
    if checkpoint.journal_id != journal_id {
        return Err(JournalHeadAnchorError::JournalIdMismatch);
    }
    if current.session_fingerprint != checkpoint.head.session_fingerprint {
        return Err(JournalHeadAnchorError::SessionFingerprintMismatch);
    }
    if current.clock_domain != checkpoint.head.clock_domain {
        return Err(JournalHeadAnchorError::ClockDomainMismatch);
    }
    if current.journal_sequence < checkpoint.head.journal_sequence {
        return Err(JournalHeadAnchorError::LocalJournalBehindAnchor);
    }
    let prefix = prefix.ok_or(JournalHeadAnchorError::AnchoredPrefixUnavailable)?;
    if prefix != checkpoint.head {
        return Err(JournalHeadAnchorError::AnchoredPrefixMismatch);
    }
    Ok(())
}
